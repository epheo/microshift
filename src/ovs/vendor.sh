#!/bin/bash
# Vendor OpenShift's br-ex setup into src/ovs, verbatim from the
# machine-config-operator commit the pinned OKD payload (versions.env) was
# built from:
#   configure-ovs.sh       moves the node's default-route NIC and its IP
#                          configuration into br-ex through NetworkManager OVS
#                          profiles, and rolls back to the original profiles
#                          when that fails.
#   nm-ignore-sdn.conf     keeps NetworkManager off the devices OVN-K owns.
#   ovs*-restart.conf      restart OVS on failure: it carries the uplink.
# scripts/bump-versions.sh reruns it; the build job fails when a committed
# file differs from what the pin gives.
set -euo pipefail
cd "$(dirname "$0")/../.."
# shellcheck disable=SC1091
source versions.env

release="${OKD_RELEASE_IMAGE}:${OKD_VERSION_TAG}"
refs="$(mktemp)"
sources="$(mktemp)"
body="$(mktemp)"
trap 'rm -f "${refs}" "${sources}" "${body}"' EXIT

# shellcheck source=src/lib/payload-source.sh
source src/lib/payload-source.sh
payload_refs

# vendor <MCO path> <yq expression> <out>: a MachineConfig file or unit entry,
# its contents behind a header naming the source. A shebang stays first.
vendor() {
    : > "${sources}"
    # MCO renders some top-level keys (enabled:) as Go templates, not YAML.
    fetch machine-config-operator "$1" | sed '/^[a-z]*: .*{{/d' | yq -e "$2" > "${body}"
    {
        if head -n 1 "${body}" | grep -q '^#!'; then head -n 1 "${body}"; fi
        echo "# Generated by src/ovs/vendor.sh from ${release}; do not edit."
        echo "# OpenShift's own, verbatim. Source:"
        sed 's/^/#   /' "${sources}"
        if head -n 1 "${body}" | grep -q '^#!'; then tail -n +2 "${body}"; else cat "${body}"; fi
    } > "$3"
    echo "vendored $3"
}

vendor templates/common/_base/files/configure-ovs-network.yaml '.contents.inline' src/ovs/configure-ovs.sh
chmod 755 src/ovs/configure-ovs.sh
vendor templates/common/_base/files/nm-ignore-sdn.yaml '.contents.inline' src/ovs/nm-ignore-sdn.conf
vendor templates/common/_base/units/ovs-vswitchd.service.yaml '.dropins[0].contents' src/ovs/ovs-vswitchd-restart.conf
vendor templates/common/_base/units/ovsdb-server.service.yaml '.dropins[0].contents' src/ovs/ovsdb-server-restart.conf
