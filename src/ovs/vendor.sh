#!/bin/bash
# Vendor OpenShift's configure-ovs.sh into src/ovs/configure-ovs.sh, verbatim
# from the machine-config-operator commit the pinned OKD payload
# (versions.env) was built from. It moves the node's default-route NIC and
# its IP configuration into br-ex through NetworkManager OVS profiles, and
# rolls back to the original profiles when that fails.
# scripts/bump-versions.sh reruns it; the build job fails when the committed
# file differs from what the pin gives.
set -euo pipefail
cd "$(dirname "$0")/../.."
# shellcheck disable=SC1091
source versions.env

release="${OKD_RELEASE_IMAGE}:${OKD_VERSION_TAG}"
out=src/ovs/configure-ovs.sh
refs="$(mktemp)"
sources="$(mktemp)"
script="$(mktemp)"
trap 'rm -f "${refs}" "${sources}" "${script}"' EXIT

# shellcheck source=src/lib/payload-source.sh
source src/lib/payload-source.sh
payload_refs

# A MachineConfig file entry: the script is its inline contents.
fetch machine-config-operator templates/common/_base/files/configure-ovs-network.yaml |
    yq -e '.contents.inline' > "${script}"

{
    head -n 1 "${script}"
    echo "# Generated by src/ovs/vendor.sh from ${release}; do not edit."
    echo "# OpenShift's own br-ex setup, verbatim. Source:"
    sed 's/^/#   /' "${sources}"
    tail -n +2 "${script}"
} > "${out}"
chmod 755 "${out}"
echo "vendored ${out} from ${release}"
