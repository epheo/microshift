#!/bin/bash
# Vendor OpenShift's own grants that MicroShift's apiserver bootstrap lacks,
# and the host-network namespace and UDN label policy its network operator
# creates, into src/rbac/openshift-parity.yaml, verbatim, from their sources
# at the commits the pinned OKD payload (versions.env) was built from: they
# move with every payload bump. scripts/bump-versions.sh reruns it; the build
# job fails when the committed file differs from what the pin gives.
set -euo pipefail
cd "$(dirname "$0")/../.."
# shellcheck disable=SC1091
source versions.env

release="${OKD_RELEASE_IMAGE}:${OKD_VERSION_TAG}"
out=src/rbac/openshift-parity.yaml
refs="$(mktemp)"
sources="$(mktemp)"
body="$(mktemp)"
trap 'rm -f "${refs}" "${sources}" "${body}"' EXIT

# The payload's image-references names each component's source and commit.
if command -v oc >/dev/null; then
    oc adm release extract --file=image-references "${release}" > "${refs}"
else
    ctr="$(podman create -q "${release}")"
    podman cp "${ctr}:/release-manifests/image-references" - | tar -xO > "${refs}"
    podman rm -f "${ctr}" >/dev/null
fi

# fetch <component> <path>: the file at the commit the payload built it from.
fetch() {
    local repo commit
    read -r repo commit < <(jq -r --arg n "$1" '.spec.tags[] | select(.name == $n) | .annotations |
        "\(.["io.openshift.build.source-location"] // "") \(.["io.openshift.build.commit.id"] // "")"' "${refs}")
    if [ -z "${repo}" ] || [ -z "${commit}" ]; then
        echo "no source or commit for $1 in ${release}" >&2
        return 1
    fi
    echo "${repo#https://} ${2} @ ${commit}" >> "${sources}"
    curl -fsSL --retry 3 "${repo/github.com/raw.githubusercontent.com}/${commit}/$2"
}

# named <names...>: the objects so named in a YAML stream on stdin, each one
# required.
named() {
    local stream name
    stream="$(cat)"
    for name in "$@"; do
        yq -e "select(.metadata.name == \"${name}\")" <<<"${stream}"
        echo "---"
    done
}

{
    # Every signed-in user: basic-user, its storage-class piece, its binding,
    # and the snapshot-class piece the CSI snapshot controller aggregates in.
    fetch openshift-apiserver test/testdata/bootstrappolicy/bootstrap_cluster_roles.yaml |
        yq '.items[] | split_doc' | named basic-user system:openshift:aggregate-to-basic-user
    fetch openshift-apiserver test/testdata/bootstrappolicy/bootstrap_cluster_role_bindings.yaml |
        yq '.items[] | split_doc' | named basic-users
    fetch cluster-csi-snapshot-controller-operator manifests/05_user_rbac.yaml |
        named system:openshift:aggregate-snapshots-to-basic-user
    # Gateway API in the stock project roles: view reads, edit and admin write.
    for role in view admin; do
        fetch cluster-ingress-operator "pkg/manifests/assets/gateway-api/aggregated-cluster-roles/${role}-cluster-role.yaml" |
            named "system:openshift:gateway-api:aggregate-to-${role}"
    done
    # NAD reads in admin. The file is a template; this one document holds none.
    fetch cluster-network-operator bindata/network/multus/002-rbac.yaml |
        awk 'BEGIN { RS = "\n---\n" } /\n  name: net-attach-def-project\n/ { print }' |
        named net-attach-def-project
    # The namespace OVN-Kubernetes is configured to hold host-network sources
    # (host-network-namespace): its label lets a NetworkPolicy admit them, a
    # host-network Gateway data plane such as portail's among them.
    for f in openshift-host-network-ns.yaml openshift-host-network-resourcequota.yaml; do
        fetch cluster-network-operator "bindata/network/ovn-kubernetes/common/${f}" | yq '.'
        echo "---"
    done
    # UserDefinedNetworks in the stock project roles (edit writes, view
    # reads; CUDNs stay cluster-admin's), and the policy that freezes a
    # namespace's primary-network label once it exists: OVN-K reads it at
    # creation only.
    for f in 009-rbac-udn-editor.yaml 010-rbac-udn-viewer.yaml udn-admission-policy.yaml; do
        fetch cluster-network-operator "bindata/network/ovn-kubernetes/common/${f}" | yq '.'
        echo "---"
    done
} > "${body}"

{
    echo "# Generated by src/rbac/vendor.sh from ${release}; do not edit."
    echo "# OpenShift's own grants that MicroShift's apiserver bootstrap lacks, and its"
    echo "# host-network namespace and UDN label policy, verbatim, so each means the"
    echo "# same on both. Sources:"
    sort -u "${sources}" | sed 's/^/#   /'
    sed '$ d' "${body}"
} > "${out}"
echo "vendored ${out} from ${release}"
